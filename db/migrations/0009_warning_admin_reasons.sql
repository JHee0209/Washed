-- 0009 — 관리자 수동 경고 사유 두 가지를 warnings.reason 에 받아들인다.
--
-- 팀 확정(2026-09-17): 경고는 「서버가 객관적으로 판정하는 것」과 「관리자가 보고
-- 판단하는 것」으로 나뉜다.
--
--   시스템 자동 : 배정 후 미인증(P3) · 수거 미완료(P5) — expiration.ts 가 찍는다
--   관리자 수동 : 순서 미준수 · 세탁물 방치           — admin-actions.ts 가 찍는다
--
-- 이 둘을 DB 에서도 구분해 두어야 관리자 화면의 「최근 사유」와 사용자 알림이
-- 무엇 때문에 받은 경고인지 말해 줄 수 있다. 그래서 값을 접지 않고 늘린다.
--
-- **기존 세 값은 그대로 남긴다.** 특히 '신고 확인' 은 새 화면에서 더는 고를 수
-- 없게 되지만, 이미 그 사유로 저장된 행이 있고 issueUsageIncidentWarning() 이
-- 여전히 쓴다 — 목록에서 빼면 과거 행이 제약을 어기게 되어 되돌릴 수 없다.
--
-- 완전히 추가적이다 — 기존 행은 전부 그대로 통과하고, 칸도 인덱스도 늘지 않는다.
-- (06-data.md 「경고」 항목의 사유 목록도 같이 고쳤다.)
--
-- CHECK 은 컬럼에 붙어 있어 이름이 warnings_reason_check 로 자동으로 붙는다.
-- 지우고 다시 만드는 것 말고는 넓힐 방법이 없다.

ALTER TABLE warnings
  DROP CONSTRAINT IF EXISTS warnings_reason_check;

ALTER TABLE warnings
  ADD CONSTRAINT warnings_reason_check
  CHECK (reason IN (
    -- 시스템 자동 (05 P6-1 · P3 · P5)
    '배정 후 미인증',
    '수거 미완료',
    -- 관리자 수동 (05 P16 · 2026-09-17 정책)
    '순서 미준수',
    '세탁물 방치',
    -- 과거 관리자 값 — 새로 부여하지는 않지만 기존 행 때문에 남긴다
    '신고 확인'
  ));
