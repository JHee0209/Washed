// 한국어 원문 — **네 언어 사전의 유일한 key 원천이다** (F37 · 05 P25).
//
// en.ts · zh.ts · ja.ts 는 `satisfies Dictionary` 로 이 객체의 key 집합을 강제받는다.
// 그래서 여기에 key 를 하나 더하면 나머지 세 파일이 컴파일 오류가 나고,
// `npx tsc --noEmit` 이 곧 「네 언어에 빠진 문장이 없는가」 검사가 된다.
//
// ── 규칙
//   · key 는 의미 기반 dot 표기다. 한국어 문장을 key 로 쓰지 않는다
//     (그 방식이 프로토타입 i18n.js 의 문제였다 · 08 · 11번)
//   · 값 안의 `{name}` 은 치환 자리다. 번역에서도 **같은 이름**을 그대로 둔다 —
//     순서는 언어마다 달라도 되지만 이름이 바뀌면 치환되지 않는다
//   · **복수형 엔진을 두지 않는다.** ko · zh · ja 는 수에 따라 말이 바뀌지 않고,
//     영어는 문구 자체를 수에 안 걸리게 적는다. ICU MessageFormat 을 들이지 않는다
//   · 사람 이름 · 호실 · 기기 이름 · 학번처럼 **사용자가 넣은 값은 번역하지 않는다**(05 P25).
//     그런 값은 key 가 아니라 `{param}` 으로 들어온다
//   · 관리자 화면 문구는 여기에 넣지 않는다 — 관리자 UI 는 한국어 고정이다

